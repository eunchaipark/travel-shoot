-- 3. 숙소 (stays)
CREATE TABLE stays (
    stay_id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '숙박시설 ID',
    operator_user_id BIGINT NOT NULL COMMENT '사용자(운영자) ID',
    stay_code VARCHAR(50) NOT NULL COMMENT '숙박시설코드',
    stay_name VARCHAR(200) NOT NULL COMMENT '숙박시설명',
    stay_type ENUM('호텔', '모텔', '펜션') NOT NULL COMMENT '숙박시설 유형',
    address VARCHAR(500) NOT NULL COMMENT '주소',
    address_detail VARCHAR(500) COMMENT '상세지역명',
    region_id BIGINT NOT NULL COMMENT '지역 ID',
    latitude DECIMAL(10, 8) NOT NULL COMMENT '위도',
    longitude DECIMAL(11, 8) NOT NULL COMMENT '경도',
    stay_description TEXT COMMENT '숙박시설 설명',
    check_in_time TIME NOT NULL DEFAULT '15:00:00' COMMENT '체크인 시간',
    check_out_time TIME NOT NULL DEFAULT '11:00:00' COMMENT '체크아웃 시간',
    reservation_notice TEXT COMMENT '예약 공지',
    average_rating DECIMAL(3, 2) NOT NULL DEFAULT 0.00 COMMENT '평균 평점',
    review_count INT NOT NULL DEFAULT 0 COMMENT '리뷰 개수',
    view_count BIGINT NOT NULL DEFAULT 0 COMMENT '조회수',
    is_active BOOLEAN NOT NULL DEFAULT TRUE COMMENT '활성 여부',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '생성일시',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',

    FOREIGN KEY (operator_user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    FOREIGN KEY (region_id) REFERENCES regions(region_id) ON DELETE RESTRICT,

    INDEX idx_stay_type (stay_type),
    INDEX idx_is_active (is_active),

    CONSTRAINT chk_rating_range CHECK (average_rating >= 0 AND average_rating <= 5),
    CONSTRAINT chk_review_count CHECK (review_count >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='숙박시설';


