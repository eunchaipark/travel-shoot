    activity_id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '관광지 ID',
    region_id BIGINT NOT NULL COMMENT '지역 ID (FK)',
    activity_name VARCHAR(200) NOT NULL COMMENT '관광지명',
    activity_type ENUM('자연관광', '문화체험', '레포츠', '맛집탐방', '쇼핑', '사진', '휴양', '축제') NOT NULL COMMENT '관광지 유형',
