-- 9. reservations (예약)
CREATE TABLE reservations (
    reservation_id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '예약 ID',
    reservation_code VARCHAR(100) UNIQUE NOT NULL COMMENT '예약번호',
    room_id BIGINT NOT NULL COMMENT '객실 ID',
    user_id BIGINT NOT NULL COMMENT '사용자 ID',
    guest_name VARCHAR(100) NOT NULL COMMENT '이용자명',
    guest_phone VARCHAR(100) NOT NULL COMMENT '이용자 전화번호',
    guest_email VARCHAR(255) NOT NULL COMMENT '예약자 이메일',
    check_in_date DATE NOT NULL COMMENT '체크인 날짜',
    check_out_date DATE NOT NULL COMMENT '체크아웃 날짜',
    guest_count INT NOT NULL COMMENT '투숙 인원',
    total_nights INT NOT NULL COMMENT '총 숙박일수',
    total_price DECIMAL(10, 2) NOT NULL COMMENT '총 결제 금액',
    reservation_status ENUM('예약확정', '이용완료', '예약취소') NOT NULL DEFAULT '예약확정' COMMENT '예약 상태',
    cancel_reason VARCHAR(100) NULL COMMENT '취소 사유',
    cancel_detail TEXT NULL COMMENT '취소 상세 사유',
    cancelled_at DATETIME NULL COMMENT '취소일시',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '생성일시',
    FOREIGN KEY (room_id) REFERENCES rooms(room_id) ON DELETE RESTRICT,
    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    INDEX idx_room (room_id),
    INDEX idx_user (user_id),
    INDEX idx_check_in_date (check_in_date),
    INDEX idx_reservation_status (reservation_status),
    CONSTRAINT chk_date_order CHECK (check_out_date > check_in_date),
    CONSTRAINT chk_guest_count CHECK (guest_count > 0),
    CONSTRAINT chk_total_nights CHECK (total_nights > 0),
    CONSTRAINT chk_total_price CHECK (total_price >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='예약';

