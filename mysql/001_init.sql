-- 5. 맛집 테이블 (restaurants)
CREATE TABLE restaurants (
    restaurant_id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '맛집 ID',
    region_id BIGINT NOT NULL COMMENT '지역 ID (FK)',
    restaurant_name VARCHAR(200) NOT NULL COMMENT '맛집명',
    food_type ENUM('한식', '중식', '일식', '양식', '카페', '해산물', '고기', '디저트') NOT NULL COMMENT '음식 유형',
    address VARCHAR(500) NOT NULL COMMENT '주소',
    address_detail VARCHAR(500) NULL COMMENT '상세주소',
    latitude DECIMAL(10, 8) NOT NULL COMMENT '위도',
    longitude DECIMAL(11, 8) NOT NULL COMMENT '경도',
    rating DECIMAL(3, 2) NOT NULL DEFAULT 0.00 COMMENT '평점 (0.00~5.00)',
    signature_menu VARCHAR(500) NULL COMMENT '대표 메뉴',
    closed_days VARCHAR(100) NULL COMMENT '휴무 요일',
    is_active BOOLEAN NOT NULL DEFAULT TRUE COMMENT '활성 여부',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '생성일시',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',
    INDEX idx_region_id (region_id),
    INDEX idx_food_type (food_type),
    INDEX idx_rating (rating DESC),
    INDEX idx_is_active (is_active),
    CONSTRAINT fk_restaurants_region FOREIGN KEY (region_id) REFERENCES regions(region_id),
    CONSTRAINT chk_restaurant_rating CHECK (rating >= 0 AND rating <= 5)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='맛집';


