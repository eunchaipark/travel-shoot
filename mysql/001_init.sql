-- 4. 객실 (rooms)
CREATE TABLE rooms (
    room_id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '객실 ID',
    stay_id BIGINT NOT NULL COMMENT '숙박 ID',
    stay_code VARCHAR(50) NOT NULL COMMENT '숙박시설코드 (S0001, S0002...)',
    room_code VARCHAR(50) NOT NULL COMMENT '객실 코드 (R0001, R0002...)',
    room_name VARCHAR(100) NOT NULL COMMENT '객실명 (스탠다드,디럭스,트윈룸,패밀리룸,프리미엄,스위트,온돌룸,로얄스위트룸)',
    room_count INT NOT NULL DEFAULT 1 COMMENT '해당 객실 개수',
    standard_capacity INT NOT NULL DEFAULT 2 COMMENT '기준 인원',
    maximum_capacity INT NOT NULL DEFAULT 4 COMMENT '최대 인원',
    check_in_time TIME NULL COMMENT '체크인 시간',
    check_out_time TIME NULL COMMENT '체크아웃 시간',
    bedroom_count INT NOT NULL DEFAULT 1 COMMENT '침실 개수',
    bathroom_count INT NOT NULL DEFAULT 1 COMMENT '욕실 개수',
    single_bed_count INT NOT NULL DEFAULT 0 COMMENT '싱글 침대 개수',
    double_bed_count INT NOT NULL DEFAULT 0 COMMENT '더블 침대 개수',
    queen_bed_count INT NOT NULL DEFAULT 0 COMMENT '퀸 침대 개수',
    king_bed_count INT NOT NULL DEFAULT 0 COMMENT '킹 침대 개수',
    weekday_price DECIMAL(10, 2) NOT NULL COMMENT '평일 요금',
    weekend_price DECIMAL(10, 2) NOT NULL COMMENT '주말 요금',
    minimum_nights INT NOT NULL DEFAULT 1 COMMENT '최소 숙박일',
    maximum_nights INT NOT NULL DEFAULT 30 COMMENT '최대 숙박일',
    room_description TEXT COMMENT '객실 설명',
    reservation_notice TEXT COMMENT '예약 공지',
    is_available BOOLEAN NOT NULL DEFAULT TRUE COMMENT '예약 가능 여부',
    view_count BIGINT NOT NULL DEFAULT 0 COMMENT '조회수',
    reservation_count INT NOT NULL DEFAULT 0 COMMENT '예약 횟수',
    is_active BOOLEAN NOT NULL DEFAULT TRUE COMMENT '활성 여부',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '생성일시',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',

    FOREIGN KEY (stay_id) REFERENCES stays(stay_id) ON DELETE CASCADE,
    INDEX idx_stay_id (stay_id),
    INDEX idx_room_code (room_code),
    INDEX idx_room_name (room_name),
    INDEX idx_is_available (is_available),
    CONSTRAINT chk_room_count CHECK (room_count > 0),
    CONSTRAINT chk_capacity CHECK (maximum_capacity >= standard_capacity),
    CONSTRAINT chk_price CHECK (weekday_price >= 0 AND weekend_price >= 0),
    CONSTRAINT chk_nights CHECK (maximum_nights >= minimum_nights AND minimum_nights >= 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
COMMENT='객실 테이블';


